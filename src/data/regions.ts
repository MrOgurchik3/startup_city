const ISO3_TO_REGION: Record<string, RegionId> = (() => {
  const out: Record<string, RegionId> = {};
  REGION_IDS.forEach((id) => {
    REGIONS[id].iso3.forEach((iso) => (out[iso] = id));
  });
  return out;
})();

export function regionForISO3(iso3: string): RegionId | null {
  return ISO3_TO_REGION[iso3] ?? null;
}

export function regionFor(id: RegionId): RegionMeta {
  return REGIONS[id];
}
